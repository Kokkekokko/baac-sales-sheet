"""Regenerate wiki/index.md for olw from this vault's nested wiki/ layout.

olw's own generate_index() only scans the top level of wiki/, so it would drop
pages in wiki/products/, wiki/categories/ and wiki/concepts/. `olw query` picks pages
from wiki/index.md, so run this after any change that adds or renames pages, and
after any olw command that rewrites wiki/index.md (ingest, compile, approve, review):

    python -I .olw/make_olw_index.py
"""
import datetime
import re
from pathlib import Path

VAULT = Path(__file__).resolve().parent.parent
WIKI = VAULT / "wiki"
SECTIONS = [
    ("Categories", "categories"),
    ("Concepts", "concepts"),
    ("Products", "products"),
]


def meta(path: Path) -> tuple[str, str]:
    s = path.read_text(encoding="utf-8")
    m = re.search(r"^title:\s*(.+)$", s, re.M)
    title = m.group(1).strip().strip('"') if m else path.stem
    m = re.search(r"> \[!summary\][^\n]*\n((?:>.*\n?)+)", s)
    summary = ""
    if m:
        summary = " ".join(l.lstrip(">").strip() for l in m.group(1).splitlines())
        summary = re.sub(r"\[\[([^\]|]+)\|([^\]]+)\]\]", r"\2", summary)
        summary = re.sub(r"\[\[([^\]]+)\]\]", r"\1", summary)
        summary = re.sub(r"\s+", " ", summary).replace("**", "").strip()
        if len(summary) > 220:
            summary = summary[:220] + "…"
    return title, summary


def entry(path: Path) -> str:
    title, summary = meta(path)
    link = f"[[{path.stem}]]" if title == path.stem else f"[[{path.stem}|{title}]]"
    return f"- {link}" + (f" — {summary}" if summary else "")


lines = [
    "---",
    "title: Wiki Index",
    "tags: [meta, index]",
    f"updated: {datetime.date.today().isoformat()}",
    "---",
    "",
    "# Wiki Index",
    "",
    "_Index for olw (`olw query`). Generated by `.olw/make_olw_index.py` — do not edit by hand. "
    "The index for people to read is `index.md` in the vault root._",
    "",
]
total = 0
for heading, sub in SECTIONS:
    files = sorted((WIKI / sub).rglob("*.md"))
    if not files:
        continue
    if sub == "products":
        lines.append(f"## {heading}")
        lines.append("")
        for cat in sorted({f.parent for f in files}):
            lines.append(f"### {cat.name}")
            for f in sorted(cat.glob("*.md")):
                lines.append(entry(f))
                total += 1
            lines.append("")
    else:
        lines.append(f"## {heading}")
        for f in files:
            lines.append(entry(f))
            total += 1
        lines.append("")

others = [f for f in sorted(WIKI.glob("*.md")) if f.name.lower() not in ("index.md", "log.md")]
if others:
    lines.append("## Other")
    for f in others:
        lines.append(entry(f))
        total += 1
    lines.append("")

lines.append(f"_{total} entries._")
(WIKI / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wiki/index.md written: {total} entries")
